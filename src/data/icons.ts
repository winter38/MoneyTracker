const BY_ID = new Map(ICON_GROUPS.flatMap((group) => group.items.map((item) => [item.id, item.path] as const)));

/** The path for an id, or undefined when the value is not one of our ids (an emoji from older data). */
export function iconPath(id: string | undefined): string | undefined {
    return id ? BY_ID.get(id) : undefined;
}

/** The groups filtered by a search query; groups left without matches are dropped. */
export function searchIcons(query: string): IconGroup[] {
    const needle = query.trim().toLowerCase();
    if (!needle) {
        return ICON_GROUPS;
    }
    return ICON_GROUPS.map((group) => ({
        name: group.name,
        items: group.items.filter((item) => `${item.id} ${item.keywords ?? ""}`.includes(needle)),
    })).filter((group) => group.items.length > 0);
}

